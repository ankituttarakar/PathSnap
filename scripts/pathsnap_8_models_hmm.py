"""## Classifier Evaluation"""

def evaluate(cands: pd.DataFrame, obs: pd.DataFrame, proba: np.ndarray):
    y = cands["label"].values
    pred = (proba >= 0.5).astype(int)
    pr, rc, f1, _ = precision_recall_fscore_support(y, pred, average="binary", zero_division=0)
    tmp = pd.DataFrame({"trip_id": cands["trip_id"].values, "pt_idx": cands["pt_idx"].values,
                        "p": proba, "y": y})
    best = tmp.loc[tmp.groupby(["trip_id", "pt_idx"])["p"].idxmax()]
    correct = int(best["y"].sum())
    n_obs, n_hit = len(obs), int(obs["hit"].sum())
    return dict(
        accuracy=accuracy_score(y, pred), precision=pr, recall=rc, f1=f1,
        macro_f1=f1_score(y, pred, average="macro"),
        log_loss=log_loss(y, np.clip(proba, 1e-6, 1 - 1e-6), labels=[0, 1]),
        top1_acc=correct / max(n_obs, 1),                      # misses count as wrong (primary)
        top1_acc_given_hit=correct / max(n_hit, 1),
        candidate_miss_rate=1 - n_hit / max(n_obs, 1),
        n_obs=n_obs, n_candidate_rows=len(cands)), confusion_matrix(y, pred, labels=[0, 1])

"""## Hmm / Viterbi Route Reconstruction"""

def transition_table(hop_pen, jump_pen, uturn_pen):
    """log-transition score for each topology code: same, 1/2/3 hops, U-turn, disconnected (never -inf,
    so an invalid transition is expensive but the decoder can always continue)."""
    return np.array([0.0, -hop_pen, -2 * hop_pen, -3 * hop_pen, -uturn_pen, -jump_pen])


def viterbi_trip(meta, proba, table, w):
    """Viterbi over the candidate arcs of one trip. Returns (hmm choice idx, classifier-only idx) per step."""
    st = meta["step_start"]
    n = len(meta["cand_arcs"])
    em = [w * np.log(np.clip(proba[st[i]:st[i + 1]], 1e-6, 1.0)) for i in range(n)]
    clf = np.array([int(e.argmax()) for e in em])
    delta, back = em[0], [None] * n
    for i in range(1, n):
        H = meta["H"][i]
        if H is None:                                           # GPS gap / chain reset
            back[i] = np.full(len(em[i]), int(delta.argmax()))
            delta = delta.max() + em[i]
        else:
            sc = delta[:, None] + table[H]
            bi = sc.argmax(0)
            delta = sc[bi, np.arange(len(bi))] + em[i]
            back[i] = bi
    path = np.zeros(n, dtype=np.int64)
    k = int(delta.argmax())
    path[n - 1] = k
    for i in range(n - 1, 0, -1):
        k = int(back[i][k])
        path[i - 1] = k
    return path, clf


def seq_metrics(metas, proba_all, table, w, which):
    """Pointwise Top-1 (reliable points; no-candidate points count as wrong), continuity, route-arc F1."""
    correct = total = pairs = connected = 0
    f1s = []
    for m in metas:
        pr = proba_all[m["row_offset"]:m["row_offset"] + m["n_rows"]]
        hmm_idx, clf_idx = viterbi_trip(m, pr, table, w)
        idx = hmm_idx if which == "hmm" else clf_idx
        arcs = np.array([m["cand_arcs"][i][k] for i, k in enumerate(idx)])
        correct += int(((arcs == m["ref_arc"]) & m["reliable"]).sum())
        total += m["n_rel_window"]
        for i in range(1, len(idx)):
            if m["H"][i] is not None:
                pairs += 1
                connected += int(m["H"][i][idx[i - 1], idx[i]] <= MAX_HOPS)
        P, R = set(arcs.tolist()), set(m["ref_arc"][m["reliable"]].tolist())
        if P and R:
            pp, rr = len(P & R) / len(P), len(P & R) / len(R)
            f1s.append(0 if pp + rr == 0 else 2 * pp * rr / (pp + rr))
    return dict(top1=correct / max(total, 1), continuity=connected / max(pairs, 1),
                route_f1=float(np.mean(f1s)) if f1s else 0.0)


def tune_decoder(metas, proba_oof):
    rows = []
    for hp, jp, up, w in itertools.product(*DECODER_GRID.values()):
        tab = transition_table(hp, jp, up)
        r = seq_metrics(metas, proba_oof, tab, w, "hmm")
        rows.append(dict(hop_pen=hp, jump_pen=jp, uturn_pen=up, emission_weight=w, **r))
    g = pd.DataFrame(rows).sort_values(["top1", "continuity"], ascending=False).reset_index(drop=True)
    return g

"""## Main"""

def main():
    np.random.seed(SEED)
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    T0 = time.time()
    cands, obs, info, seq_df, metas = build_dataset()

    print("\n=== DATASET INVENTORY ===")
    inv = info.groupby("split").agg(trips=("trip_id", "count"), gps_points=("points", "sum"),
                                    median_points=("points", "median"), median_nodes=("nodes", "median"),
                                    median_arcs=("arcs", "median"), unreliable_labels=("unreliable_labels", "sum"),
                                    max_gap_s=("max_time_gap_s", "max"), mean_pct_1s=("pct_1s_steps", "mean"))
    print(inv.round(2).to_string())
    for s in ["train", "test"]:
        o = obs[obs.split == s]
        print(f"[{s}] sampled observations: {len(o):,} | candidate rows: {(cands.split == s).sum():,} | "
              f"candidate miss rate: {1 - o.hit.mean():.3%}")
    print(f"Features used: {len(FEATURES)}  ->  {FEATURES}")
    info.to_csv(OUTPUT_DIR / "trip_inventory.csv", index=False)
    inv.to_csv(OUTPUT_DIR / "dataset_inventory.csv")

    tr_c, te_c = cands[cands.split == "train"].reset_index(drop=True), cands[cands.split == "test"].reset_index(drop=True)
    tr_o, te_o = obs[obs.split == "train"], obs[obs.split == "test"]
    Xtr, ytr, Xte = tr_c[FEATURES].values.astype(np.float32), tr_c["label"].values, te_c[FEATURES].values.astype(np.float32)
    groups = tr_c["trip_id"].values

    seq_tr_mask = (seq_df.split == "train").values
    seq_te_mask = ~seq_tr_mask
    Xs_tr, Xs_te = seq_df.loc[seq_tr_mask, FEATURES].values.astype(np.float32), seq_df.loc[seq_te_mask, FEATURES].values.astype(np.float32)
    seq_tr_trip = seq_df.loc[seq_tr_mask, "trip_id"].values
    # metas re-based so that row_offset is relative to the train-only / test-only seq tables
    def rebase(ms):
        out, off = [], 0
        for m in ms:
            m2 = dict(m); m2["row_offset"] = off; off += m["n_rows"]; out.append(m2)
        return out
    metas_tr = rebase([m for m in metas if m["split"] == "train"])
    metas_te = rebase([m for m in metas if m["split"] == "test"])

    try:
        splitter = GroupKFold(n_splits=CV_FOLDS, shuffle=True, random_state=SEED)
    except TypeError:
        splitter = GroupKFold(n_splits=CV_FOLDS)
    folds = list(splitter.split(Xtr, ytr, groups))

    models = get_models()
    fold_rows, summary, test_conf = [], [], {}
    oof_seq, test_seq = {}, {}
    print(f"\n=== TRAINING 8 MODELS ({CV_FOLDS}-fold group CV on {len(set(groups))} train trips, "
          f"then test on {te_o.trip_id.nunique()} student-test trips) ===")
    t_models = time.time()
    for mi, (name, (family, params, make)) in enumerate(models.items()):
        t_start = time.time()
        fold_metrics = []
        oof = np.zeros(len(Xs_tr))
        for f, (tri, vai) in enumerate(folds):
            m = make(params)
            m.fit(Xtr[tri], ytr[tri])
            vc = tr_c.iloc[vai]
            val_trips = set(vc.trip_id)
            vo = tr_o[tr_o.trip_id.isin(val_trips)]
            met, _ = evaluate(vc, vo, m.predict_proba(Xtr[vai])[:, 1])
            sm = np.isin(seq_tr_trip, list(val_trips))
            if sm.any():
                oof[sm] = m.predict_proba(Xs_tr[sm])[:, 1]
            fold_metrics.append(met)
            fold_rows.append(dict(model=name, fold=f, **met))
            print(f"   {name} fold {f + 1}/{CV_FOLDS} done | model elapsed {fmt(time.time() - t_start)}", flush=True)
        oof_seq[name] = oof
        cv = pd.DataFrame(fold_metrics)
        t1 = time.time()
        final = make(params).fit(Xtr, ytr)
        train_time = time.time() - t1
        t2 = time.time()
        proba = final.predict_proba(Xte)[:, 1]
        infer_time = time.time() - t2
        test_seq[name] = final.predict_proba(Xs_te)[:, 1]
        tmet, cm = evaluate(te_c, te_o, proba)
        test_conf[name] = cm.tolist()
        row = dict(model=name, family=family, config=json.dumps(params),
                   cv_top1_mean=cv.top1_acc.mean(), cv_top1_std=cv.top1_acc.std(),
                   cv_f1_mean=cv.f1.mean(), cv_logloss_mean=cv.log_loss.mean(), cv_logloss_std=cv.log_loss.std(),
                   cv_miss_rate=cv.candidate_miss_rate.mean(),
                   **{f"test_{k}": v for k, v in tmet.items() if k not in ("n_obs", "n_candidate_rows")},
                   train_time_s=train_time, infer_time_s=infer_time, infer_us_per_row=1e6 * infer_time / len(Xte),
                   total_cv_time_s=time.time() - t_start)
        summary.append(row)
        done = mi + 1
        el = time.time() - t_models
        print(f"{name:26s} CV top1 {row['cv_top1_mean']:.4f}±{row['cv_top1_std']:.4f} | "
              f"CV logloss {row['cv_logloss_mean']:.4f} | TEST top1 {row['test_top1_acc']:.4f} "
              f"F1 {row['test_f1']:.4f} logloss {row['test_log_loss']:.4f} | train {train_time:.1f}s | "
              f"[{done}/8 models, elapsed {fmt(el)}]", flush=True)

    res = pd.DataFrame(summary)

    # ---------------- HMM stage
    print(f"\n=== HMM / VITERBI (decoder tuned on out-of-fold train predictions; "
          f"grid of {len(list(itertools.product(*DECODER_GRID.values())))} settings per model) ===")
    hmm_rows, grid_rows = [], []
    for name in models:
        tg = time.time()
        g = tune_decoder(metas_tr, oof_seq[name])
        g.insert(0, "model", name)
        grid_rows.append(g)
        best = g.iloc[0]
        tab = transition_table(best.hop_pen, best.jump_pen, best.uturn_pen)
        clf_te = seq_metrics(metas_te, test_seq[name], tab, best.emission_weight, "clf")
        hmm_te = seq_metrics(metas_te, test_seq[name], tab, best.emission_weight, "hmm")
        clf_oof = seq_metrics(metas_tr, oof_seq[name], tab, best.emission_weight, "clf")
        hmm_rows.append(dict(
            model=name, hop_pen=best.hop_pen, jump_pen=best.jump_pen, uturn_pen=best.uturn_pen,
            emission_weight=best.emission_weight,
            oof_top1_clf=clf_oof["top1"], oof_top1_hmm=best.top1,
            test_top1_clf=clf_te["top1"], test_top1_hmm=hmm_te["top1"],
            test_top1_gain=hmm_te["top1"] - clf_te["top1"],
            test_continuity_clf=clf_te["continuity"], test_continuity_hmm=hmm_te["continuity"],
            test_route_f1_clf=clf_te["route_f1"], test_route_f1_hmm=hmm_te["route_f1"]))
        print(f"{name:26s} test Top-1 {clf_te['top1']:.4f} -> {hmm_te['top1']:.4f} (HMM) | continuity "
              f"{clf_te['continuity']:.3f} -> {hmm_te['continuity']:.3f} | route F1 {clf_te['route_f1']:.3f} -> "
              f"{hmm_te['route_f1']:.3f} | {fmt(time.time() - tg)}", flush=True)
    hmm = pd.DataFrame(hmm_rows)
    hmm.to_csv(OUTPUT_DIR / "hmm_comparison.csv", index=False)
    pd.concat(grid_rows).to_csv(OUTPUT_DIR / "decoder_grid_results.csv", index=False)

    res = res.merge(hmm[["model", "test_top1_hmm", "test_continuity_hmm", "test_route_f1_hmm"]], on="model")
    res = res.sort_values(["cv_top1_mean", "cv_logloss_mean"], ascending=[False, True])
    res.to_csv(OUTPUT_DIR / "model_comparison.csv", index=False)
    pd.DataFrame(fold_rows).to_csv(OUTPUT_DIR / "cv_fold_results.csv", index=False)
    json.dump(test_conf, open(OUTPUT_DIR / "test_confusion_matrices.json", "w"), indent=2)
    json.dump(dict(seed=SEED, quick_mode=QUICK_MODE, cand_radius_m=CAND_RADIUS_M, max_candidates=MAX_CANDIDATES,
                   align_radius_m=ALIGN_RADIUS_M, label_max_dist_m=LABEL_MAX_DIST_M,
                   max_points_per_trip=MAX_POINTS_PER_TRIP, cv_folds=CV_FOLDS, seq_len_train=SEQ_LEN_TRAIN,
                   seq_len_test=SEQ_LEN_TEST, max_hops=MAX_HOPS, gap_s=GAP_S, decoder_grid=DECODER_GRID,
                   features=FEATURES, models={k: dict(family=v[0], params=v[1]) for k, v in models.items()}),
              open(OUTPUT_DIR / "run_config.json", "w"), indent=2)

    show = ["model", "cv_top1_mean", "cv_top1_std", "cv_logloss_mean", "test_top1_acc", "test_top1_hmm",
            "test_f1", "test_log_loss", "train_time_s"]
    print("\n=== RANKING (by CV Top-1, tie-break CV log loss; model choice uses CV only, not the test set) ===")
    print(res[show].round(4).to_string(index=False))
    print(f"\nBest by primary metric: {res.iloc[0]['model']}")
    print(f"Total run time: {fmt(time.time() - T0)} | results saved in: {OUTPUT_DIR.resolve()}")
    return res, hmm

