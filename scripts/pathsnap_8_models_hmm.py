"""## Road-Network Topology Helpers"""

class ArcGraph:
    """Directed arc graph: topological relation between two arcs (used by a feature and by the HMM)."""

    def __init__(self, A, B, n_nodes):
        self.A, self.B = A, B
        self.order = np.argsort(A, kind="stable")
        self.ptr = np.searchsorted(A[self.order], np.arange(n_nodes + 1))
        self.memo = {}

    def _out(self, node):
        return self.order[self.ptr[node]:self.ptr[node + 1]]

    def _reach(self, a):
        r = self.memo.get(a)
        if r is None:
            r, frontier = {}, [a]
            for h in range(1, MAX_HOPS + 1):
                nxt = []
                for x in frontier:
                    for y in self._out(self.B[x]):
                        y = int(y)
                        if y != a and y not in r:
                            r[y] = h
                            nxt.append(y)
                frontier = nxt
            self.memo[a] = r
        return r

    def code(self, a, b):
        """0 same arc | 1..MAX_HOPS forward hops | 4 U-turn (reverse arc) | 5 not connected."""
        a, b = int(a), int(b)
        if a == b:
            return 0
        if self.A[b] == self.B[a] and self.B[b] == self.A[a]:
            return 4
        h = self._reach(a).get(b)
        return h if h is not None else 5

    def matrix(self, prev_arcs, cur_arcs):
        return np.array([[self.code(a, b) for b in cur_arcs] for a in prev_arcs], dtype=np.int8)

"""## Per-Trip Processing"""

def project(lon, lat, lon0, lat0):
    """Local equirectangular projection to metres (accurate for city-scale trips; per-trip origin)."""
    return np.c_[(lon - lon0) * np.cos(np.radians(lat0)) * 111320.0, (lat - lat0) * 110540.0]


def align_to_route(pt_geoms, route_lines):
    """Monotone alignment of each GPS point to an arc of the reference route (Viterbi-style DP).
    Returns the index into the route for each point. Route order is respected (no going backwards)."""
    n = len(pt_geoms)
    tree = STRtree(route_lines)
    qi, ti = tree.query(pt_geoms, predicate="dwithin", distance=ALIGN_RADIUS_M)
    d = shapely.distance(pt_geoms[qi], route_lines[ti])
    order = np.argsort(qi, kind="stable")
    qi, ti, d = qi[order], ti[order], d[order]
    starts = np.searchsorted(qi, np.arange(n + 1))
    cj, cd = [None] * n, [None] * n
    for i in range(n):
        s, e = starts[i], starts[i + 1]
        if e > s:
            cj[i], cd[i] = ti[s:e], d[s:e]
    miss = np.where(starts[1:] == starts[:-1])[0]
    if len(miss):
        near = tree.nearest(pt_geoms[miss])
        dm = shapely.distance(pt_geoms[miss], route_lines[near])
        for k, i in enumerate(miss):
            cj[i], cd[i] = np.array([near[k]]), np.array([dm[k]])
    back = []
    prev_j, prev_cost = cj[0], cd[0].astype(float)
    for i in range(1, n):
        j, dd = cj[i], cd[i]
        diff = j[:, None] - prev_j[None, :]
        pen = np.where(diff >= 0, 2.0 * np.maximum(diff - 1, 0), 30.0 * (-diff))
        tot = prev_cost[None, :] + pen
        bi = tot.argmin(1)
        prev_cost = dd + tot[np.arange(len(j)), bi]
        back.append(bi)
        prev_j = j
    path = np.zeros(n, dtype=np.int64)
    k = int(prev_cost.argmin())
    path[n - 1] = cj[n - 1][k]
    for i in range(n - 1, 0, -1):
        k = int(back[i - 1][k])
        path[i - 1] = cj[i - 1][k]
    return path


def process_trip(split, tid, track_path: Path):
    base = track_path.with_suffix("")
    tr = np.loadtxt(track_path, ndmin=2)
    nodes = np.loadtxt(base.with_suffix(".nodes"), ndmin=2)
    arcs = np.loadtxt(base.with_suffix(".arcs"), dtype=np.int64, ndmin=2)
    route = np.loadtxt(base.with_suffix(".route"), dtype=np.int64, ndmin=1)

    tr = tr[np.isfinite(tr).all(1)]
    if not (np.diff(tr[:, 2]) >= 0).all():
        tr = tr[np.argsort(tr[:, 2], kind="stable")]
    assert arcs.max() < len(nodes) and route.max() < len(arcs), "index out of range"

    lon0, lat0 = np.median(tr[:, 0]), np.median(tr[:, 1])
    pts = project(tr[:, 0], tr[:, 1], lon0, lat0)
    nxy = project(nodes[:, 0], nodes[:, 1], lon0, lat0)
    t = tr[:, 2]
    n = len(pts)

    A, B = arcs[:, 0], arcs[:, 1]
    lines = shapely.linestrings(np.stack([nxy[A], nxy[B]], axis=1))
    arc_len = shapely.length(lines)
    arc_bearing = np.arctan2(nxy[B, 1] - nxy[A, 1], nxy[B, 0] - nxy[A, 0])
    key = A * len(nodes) + B
    has_rev = np.isin(B * len(nodes) + A, key).astype(np.float32)
    pt_geoms = shapely.points(pts)
    G = ArcGraph(A, B, len(nodes))
    tree = STRtree(lines)

    # ---- reference label per point (assumption: nearest route arc, in route order)
    j = align_to_route(pt_geoms, lines[route])
    ref_arc = route[j]
    ref_dist = shapely.distance(pt_geoms, lines[ref_arc])
    reliable = ref_dist <= LABEL_MAX_DIST_M

    # ---- per-point kinematics
    lo, hi = np.clip(np.arange(n) - 2, 0, n - 1), np.clip(np.arange(n) + 2, 0, n - 1)
    vec, dtw = pts[hi] - pts[lo], t[hi] - t[lo]
    mv = np.hypot(vec[:, 0], vec[:, 1])
    ok = (dtw > 0) & (dtw <= 20)
    speed = np.where(ok, mv / np.where(dtw > 0, dtw, 1), 0.0)
    head_valid = ok & (mv > 3.0)
    heading = np.arctan2(vec[:, 1], vec[:, 0])
    dt_prev = np.r_[0.0, np.diff(t)]
    i0, i1 = np.clip(np.arange(n) - 3, 0, n - 1), np.clip(np.arange(n) + 3, 0, n - 1)
    vin, vout = pts - pts[i0], pts[i1] - pts
    nin, nout = np.hypot(vin[:, 0], vin[:, 1]), np.hypot(vout[:, 0], vout[:, 1])
    cosv = (vin * vout).sum(1) / np.maximum(nin * nout, 1e-9)
    turn_cos = np.where((nin > 2) & (nout > 2), cosv, 1.0)       # 1 = straight, <1 = turning

    def make_cands(idx):
        """Candidate rows + 20 features for the GPS points `idx` (sorted by point, then distance)."""
        qi, ti = tree.query(pt_geoms[idx], predicate="dwithin", distance=CAND_RADIUS_M)
        if len(qi) == 0:
            return None
        pi = idx[qi]
        c = pd.DataFrame({"pt_idx": pi, "arc_id": ti, "dist": shapely.distance(pt_geoms[pi], lines[ti])})
        c = c.sort_values(["pt_idx", "dist"], kind="stable")
        c["dist_rank"] = c.groupby("pt_idx").cumcount()
        c = c[c.dist_rank < MAX_CANDIDATES].reset_index(drop=True)
        c["n_cands"] = c.groupby("pt_idx")["dist"].transform("size")
        c["dist_minus_min"] = c["dist"] - c.groupby("pt_idx")["dist"].transform("min")
        p, a = c["pt_idx"].values, c["arc_id"].values
        c["head_cos"] = np.where(head_valid[p], np.cos(heading[p] - arc_bearing[a]), 0.0)
        c["head_valid"] = head_valid[p].astype(np.float32)
        c["turn_cos"] = turn_cos[p]
        c["frac"] = shapely.line_locate_point(lines[a], pt_geoms[p], normalized=True)
        c["arc_len"] = arc_len[a]
        c["speed"] = speed[p]
        c["dt_prev"] = dt_prev[p]
        c["has_reverse"] = has_rev[a]
        ax_, ay_ = nxy[A[a], 0], nxy[A[a], 1]
        cross = (nxy[B[a], 0] - ax_) * (pts[p, 1] - ay_) - (nxy[B[a], 1] - ay_) * (pts[p, 0] - ax_)
        c["signed_offset"] = np.sign(cross) * c["dist"]
        for name, off in [("prev", -1), ("next", 1), ("prev3", -3), ("next3", 3)]:
            q = np.clip(p + off, 0, n - 1)
            c[f"dist_{name}"] = shapely.distance(pt_geoms[q], lines[a])
            if abs(off) == 1:
                c[f"frac_{name}"] = shapely.line_locate_point(lines[a], pt_geoms[q], normalized=True)
        c["dist_nb_mean"] = c[["dist_prev", "dist_next", "dist_prev3", "dist_next3"]].mean(1)
        c["along_move"] = (c["frac_next"] - c["frac_prev"]) * c["arc_len"]
        up = np.unique(p)                                             # topology vs previous point's nearest arc
        near_prev = tree.nearest(pt_geoms[np.clip(up - 1, 0, n - 1)])[np.searchsorted(up, p)]
        c["connect_prev"] = np.minimum([G.code(x, y) for x, y in zip(near_prev, a)], 4).astype(np.float32)
        c["label"] = (a == ref_arc[p]).astype(np.int8)
        return c[["pt_idx", "arc_id", "label"] + FEATURES]

    def tag(c):
        c.insert(0, "trip_id", tid)
        c.insert(1, "split", split)
        return c

    # ---- (a) classifier training/eval rows: evenly sampled reliable points
    rel_idx = np.where(reliable)[0]
    if len(rel_idx) > MAX_POINTS_PER_TRIP:
        rel_idx = rel_idx[np.linspace(0, len(rel_idx) - 1, MAX_POINTS_PER_TRIP).astype(int)]
    c = make_cands(rel_idx)
    if c is None:
        raise ValueError("no candidates generated")
    c = tag(c)
    hit = set(c.loc[c.label == 1, "pt_idx"].tolist())
    obs = pd.DataFrame({"trip_id": tid, "split": split, "pt_idx": rel_idx,
                        "hit": [int(i) in hit for i in rel_idx]})

    # ---- (b) HMM sequence: consecutive points (a window for train trips, whole trip for test)
    seq_len = SEQ_LEN_TRAIN if split == "train" else SEQ_LEN_TEST
    if seq_len is None or seq_len >= n:
        s0, s1 = 0, n
    else:
        s0 = int(0.3 * (n - seq_len))
        s1 = s0 + seq_len
    win = np.arange(s0, s1)
    cs = make_cands(win)
    meta, seq_df = None, None
    if cs is not None:
        cs = tag(cs)
        pt = cs.pt_idx.values
        uniq, first = np.unique(pt, return_index=True)
        starts = np.r_[first, len(pt)]
        arcs_all = cs.arc_id.values
        cand_arcs = [arcs_all[starts[k]:starts[k + 1]] for k in range(len(uniq))]
        Hm, gap = [None] * len(uniq), np.zeros(len(uniq), bool)
        for k in range(1, len(uniq)):
            if t[uniq[k]] - t[uniq[k - 1]] > GAP_S:
                gap[k] = True
            else:
                Hm[k] = G.matrix(cand_arcs[k - 1], cand_arcs[k])
        meta = dict(trip_id=tid, split=split, steps=uniq, cand_arcs=cand_arcs, H=Hm, gap=gap,
                    step_start=starts, ref_arc=ref_arc[uniq], reliable=reliable[uniq],
                    n_rel_window=int(reliable[win].sum()), n_rows=len(cs))
        seq_df = cs

    info = dict(trip_id=tid, split=split, points=n, nodes=len(nodes), arcs=len(arcs), route_arcs=len(route),
                unreliable_labels=int((~reliable).sum()), sampled_points=len(rel_idx),
                max_time_gap_s=float(np.diff(t).max()) if n > 1 else 0.0,
                pct_1s_steps=float((np.diff(t) == 1).mean()) if n > 1 else 1.0)
    return c, obs, info, seq_df, meta


def build_dataset():
    cache = OUTPUT_DIR / (f"dataset_cache_v2_{MAX_POINTS_PER_TRIP}_{int(CAND_RADIUS_M)}_{MAX_CANDIDATES}_"
                          f"{SEQ_LEN_TRAIN}_{SEQ_LEN_TEST}.pkl")
    if USE_CACHE and cache.exists():
        print(f"Loading cached dataset: {cache}")
        return pd.read_pickle(cache)
    root = resolve_data_root()
    trips = find_trips(root)
    print(f"Found {sum(s == 'train' for s, _, _ in trips)} train trips and "
          f"{sum(s == 'test' for s, _, _ in trips)} test trips under {root}")
    if not trips:
        raise FileNotFoundError("No .track files found - check the folder structure (train/ and test/).")
    C, O, I, S, M = [], [], [], [], []
    t0 = time.time()
    for k, (split, tid, path) in enumerate(trips, 1):
        try:
            c, o, i, s, m = process_trip(split, tid, path)
            C.append(c); O.append(o); I.append(i)
            if m is not None:
                S.append(s); M.append(m)
        except Exception as e:
            print(f"  ! skipped {split}/{tid}: {type(e).__name__}: {e}")
        if k % 10 == 0 or k == len(trips):
            el = time.time() - t0
            print(f"  processed {k}/{len(trips)} trips | elapsed {fmt(el)} | est. remaining {fmt(el / k * (len(trips) - k))}")
    off = 0
    for m in M:
        m["row_offset"] = off
        off += m["n_rows"]
    data = (pd.concat(C, ignore_index=True), pd.concat(O, ignore_index=True), pd.DataFrame(I),
            pd.concat(S, ignore_index=True), M)
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    pd.to_pickle(data, cache)
    return data

